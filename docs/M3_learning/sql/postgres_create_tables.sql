-- CyberLab (M3 - Learning) : création des tables courses et progress, version PostgreSQL / Supabase.
-- Sans risque : "IF NOT EXISTS" ne touche pas une table qui existe déjà (celle de M1 reste intacte).
-- À exécuter AVANT courses_content_postgres.sql.
-- Si la table progress existe déjà sans la colonne parties_terminees, exécute ensuite postgres_add_column.sql.

CREATE TABLE IF NOT EXISTS courses (
    id          INTEGER PRIMARY KEY,
    titre       TEXT    NOT NULL,
    description TEXT,
    contenu     TEXT    NOT NULL,
    ordre       INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS progress (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER   NOT NULL,
    course_id         INTEGER   NOT NULL,
    termine           INTEGER   NOT NULL DEFAULT 0,   -- 0 ou 1 (pas BOOLEAN)
    parties_terminees INTEGER   NOT NULL DEFAULT 0,   -- nombre de parties terminées du cours
    date              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, course_id)
);

